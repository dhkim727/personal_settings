#!/usr/bin/env python3
"""
AMD GPU 커스텀 해상도 확인·설정 스크립트 (Ubuntu 24.04, EDID 오버라이드 방식)

  python3 amd_custom_mode.py check           확인만 (아무것도 안 바꿈, sudo로 실행하면 링크·현재 모드까지)
  sudo python3 amd_custom_mode.py install    확인 후 설정 (EDID 생성 → 펌웨어·initramfs·GRUB 등록)
  sudo python3 amd_custom_mode.py uninstall  설정 제거 (재부팅하면 원래 EDID로 돌아감)

옵션  --connector DP-1   대상 커넥터 지정 (기본: 연결된 모니터 1번)
      --yes              확인 질문 생략
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

# ── 타이밍: Active, Front porch, Sync, Back porch, 극성(+ 이면 True) ──
H_ACTIVE, H_FP, H_SYNC, H_BP, H_POS = 3840, 8, 32, 40, True
V_ACTIVE, V_FP, V_SYNC, V_BP, V_POS = 2160, 232, 8, 6, False
REFRESH_HZ = 222.0
FORCE_8BPC = True   # EDID 색심도를 8bit로 표기 → amdgpu가 8bpc 비압축 출력 (10bit+DSC 방지)

SYS_DRM = Path("/sys/class/drm")
DEBUG_DRI = Path("/sys/kernel/debug/dri")
FW_ROOT = Path("/lib/firmware")
FW_DIR = FW_ROOT / "edid"
HOOK = Path("/etc/initramfs-tools/hooks/custom-edid")
GRUB_DROPIN = Path("/etc/default/grub.d/99-custom-edid.cfg")
GRUB_MAIN = Path("/etc/default/grub")
GRUB_CFG = Path("/boot/grub/grub.cfg")
CMDLINE = Path("/proc/cmdline")
LOCKDOWN = Path("/sys/kernel/security/lockdown")

HB, VB = H_FP + H_SYNC + H_BP, V_FP + V_SYNC + V_BP
HT, VT = H_ACTIVE + HB, V_ACTIVE + VB
T_H = (H_ACTIVE, H_ACTIVE + H_FP, H_ACTIVE + H_FP + H_SYNC, HT)
T_V = (V_ACTIVE, V_ACTIVE + V_FP, V_ACTIVE + V_FP + V_SYNC, VT)
CLK_KHZ = round(HT * VT * REFRESH_HZ / 10_000) * 10
NEED_GBPS = CLK_KHZ * 24 / 1e6                     # 8bpc RGB 기준 필요 대역폭
RATES = {0x06: "RBR", 0x0A: "HBR", 0x14: "HBR2", 0x1E: "HBR3",
         1000: "UHBR10", 1350: "UHBR13.5", 2000: "UHBR20"}
HOOK_SH = """#!/bin/sh
# generated by amd_custom_mode.py
[ "$1" = prereqs ] && exit 0
mkdir -p "${DESTDIR}/lib/firmware/edid"
for f in /lib/firmware/edid/custom-*.bin; do
    [ -e "$f" ] && cp "$f" "${DESTDIR}/lib/firmware/edid/"
done
exit 0
"""


def ok(m): print(f"  ✓ {m}")
def warn(m): print(f"  ! {m}")
def info(m): print(f"  · {m}")
def head(m): print(f"\n[{m}]")


def die(m):
    print(f"\n✗ {m}")
    sys.exit(1)


def run(cmd):
    print("  $ " + " ".join(cmd))
    return subprocess.run(cmd).returncode == 0


def initrd_has(name):
    img = f"/boot/initrd.img-{os.uname().release}"
    r = subprocess.run(["lsinitramfs", img], capture_output=True, text=True)
    return name in r.stdout


def read_dbg(path):
    """debugfs 읽기 (권한/lockdown으로 막히면 None)"""
    try:
        fd = os.open(path, os.O_RDONLY)
    except OSError:
        return None
    data = b""
    try:
        while chunk := os.read(fd, 65536):
            data += chunk
    except OSError:
        pass
    finally:
        os.close(fd)
    return data.replace(b"\0", b"").decode(errors="replace") or None


# ───────────────────────── EDID ─────────────────────────
def csum(b):
    return (-sum(b)) & 0xFF


def edid_ok(e):
    return (len(e) >= 128 and e[:8] == b"\x00\xff\xff\xff\xff\xff\xff\x00"
            and e[126] < 255 and len(e) >= 128 * (e[126] + 1))


def descriptors(e, tag):
    return [e[o:o + 18] for o in (54, 72, 90, 108) if e[o:o + 3] == b"\0\0\0" and e[o + 3] == tag]


def edid_name(e):
    for d in descriptors(e, 0xFC):
        return d[5:18].split(b"\n")[0].decode("ascii", "replace").strip()
    return "(이름 없음)"


def edid_bpc(e):
    if e[19] >= 4 and e[20] & 0x80:
        return {1: 6, 2: 8, 3: 10, 4: 12, 5: 14, 6: 16}.get((e[20] >> 4) & 7)
    return None


def edid_range(e):
    for d in descriptors(e, 0xFD):
        f = d[4]
        return (d[5] + (255 if (f & 3) == 3 else 0), d[6] + (255 if f & 2 else 0),
                d[7] + (255 if (f & 12) == 12 else 0), d[8] + (255 if f & 8 else 0), d[9] * 10)
    return None


def edid_exts(e):
    names = {0x02: "CTA-861", 0x70: "DisplayID", 0xF0: "Block Map"}
    out = []
    for i in range(1, e[126] + 1):
        b = e[128 * i:128 * i + 2]
        n = names.get(b[0], hex(b[0]))
        out.append(f"{n} {b[1] >> 4}.{b[1] & 15}" if b[0] == 0x70 else n)
    return out


def displayid_timings(e):
    """커널과 같은 방식으로 DisplayID Type I / VII 상세 타이밍을 해석"""
    out = []
    for i in range(1, e[126] + 1):
        b = e[128 * i:128 * i + 128]
        if b[0] != 0x70:
            continue
        end, j = min(5 + b[2], 126), 5
        while j + 3 <= end and j + 3 + b[j + 2] <= end:
            tag, n = b[j], b[j + 2]
            if tag in (0x03, 0x22) and n % 20 == 0:
                for k in range(n // 20):
                    t = b[j + 3 + 20 * k:j + 23 + 20 * k]
                    w = [t[o] | t[o + 1] << 8 for o in range(4, 20, 2)]
                    clk = (t[0] | t[1] << 8 | t[2] << 16) + 1
                    ha, va = w[0] + 1, w[4] + 1
                    hs, vs = ha + (w[2] & 0x7FFF) + 1, va + (w[6] & 0x7FFF) + 1
                    out.append({"clk": clk if tag == 0x22 else clk * 10,
                                "h": (ha, hs, hs + w[3] + 1, ha + w[1] + 1),
                                "v": (va, vs, vs + w[7] + 1, va + w[5] + 1),
                                "hpos": bool(w[2] & 0x8000), "vpos": bool(w[6] & 0x8000)})
            j += 3 + n
    return out


def is_target(t):
    return (t["h"] == T_H and t["v"] == T_V and t["hpos"] == H_POS
            and t["vpos"] == V_POS and abs(t["clk"] - CLK_KHZ) <= 10)


def has_target(e):
    return any(is_target(t) for t in displayid_timings(e))


def force_8bpc(e):
    e = bytearray(e)
    if FORCE_8BPC and e[19] >= 4 and e[20] & 0x80:
        e[20] = (e[20] & 0x8F) | 0x20            # bit 6:4 = 010 → 8 bpc
        e[127] = csum(e[:127])
    return bytes(e)


def build_edid(base):
    """원본 EDID 뒤에 DisplayID 확장 블록(목표 타이밍)을 붙인다"""
    e = bytearray(base[:128 * (base[126] + 1)])
    n_ext = e[126]
    dids = [i for i in range(1, n_ext + 1) if e[128 * i] == 0x70]
    ver = e[128 * dids[0] + 1] if dids else 0x13
    type7 = ver >= 0x20                           # DisplayID 2.x → Type VII(1 kHz), 1.x → Type I(10 kHz)
    clk = round(HT * VT * REFRESH_HZ / (1_000 if type7 else 10_000))
    t = list((clk - 1).to_bytes(3, "little")) + [0x04]          # 16:9, 프로그레시브
    for v in (H_ACTIVE - 1, HB - 1, (H_FP - 1) | (H_POS << 15), H_SYNC - 1,
              V_ACTIVE - 1, VB - 1, (V_FP - 1) | (V_POS << 15), V_SYNC - 1):
        t += v.to_bytes(2, "little")
    blk = [0x22 if type7 else 0x03, 0x00, len(t)] + t
    sec = [ver, 121, 0x00 if dids else 0x03, 0x00] + blk + [0] * (121 - len(blk))
    sec.append(csum(sec))
    ext = [0x70] + sec
    ext.append(csum(ext))
    if dids and e[128 * dids[0] + 2] <= 121:     # 기존 DisplayID 기본 섹션의 Extension Count +1
        o = 128 * dids[0]
        e[o + 4] = (e[o + 4] + 1) & 0xFF
        end = o + 5 + e[o + 2]
        e[end] = csum(e[o + 1:end])
        e[o + 127] = csum(e[o:o + 127])
    e[126] = n_ext + 1
    e[127] = csum(e[:127])
    return force_8bpc(bytes(e) + bytes(ext))


# ──────────────────────── 시스템 ────────────────────────
def os_name():
    try:
        for line in Path("/etc/os-release").read_text().splitlines():
            if line.startswith("PRETTY_NAME="):
                return line.split("=", 1)[1].strip('"')
    except OSError:
        pass
    return "?"


def gpu_name(card):
    pci = (card / "device").resolve().name
    try:
        out = subprocess.run(["lspci", "-s", pci], capture_output=True, text=True).stdout
        return out.split(": ", 1)[1].strip() if ": " in out else pci
    except OSError:
        return pci


def amd_cards():
    cards = []
    for c in sorted(SYS_DRM.glob("card[0-9]*")):
        if "-" not in c.name and (c / "device" / "driver").resolve().name == "amdgpu":
            cards.append(c)
    return cards


def connected(cards):
    out = []
    for c in cards:
        for p in sorted(SYS_DRM.glob(c.name + "-*")):
            try:
                if (p / "status").read_text().strip() == "connected":
                    out.append((c, p.name[len(c.name) + 1:], p))
            except OSError:
                pass
    return out


def read_edid(cpath):
    try:
        return (cpath / "edid").read_bytes()
    except OSError:
        return b""


def pick(args):
    cards = amd_cards()
    if not cards:
        die("amdgpu 드라이버로 동작하는 GPU를 찾지 못했습니다.")
    conns = connected(cards)
    if args.connector:
        conns = [x for x in conns if x[1] == args.connector]
        if not conns:
            die(f"{args.connector} 에 연결된 모니터가 없습니다.")
    if not conns:
        die("AMD GPU에 연결된 모니터를 찾지 못했습니다.")
    if len(conns) > 1:
        print("연결된 모니터:")
        for i, (c, n, p) in enumerate(conns, 1):
            print(f"  {i}) {n}  {edid_name(read_edid(p))}")
        s = (input("적용할 모니터 번호 [1]: ").strip() if sys.stdin.isatty() else "") or "1"
        if not s.isdigit() or not 1 <= int(s) <= len(conns):
            die("잘못된 번호입니다.")
        return conns[int(s) - 1]
    return conns[0]


def cmdline_override(conn):
    """현재 부팅의 drm.edid_firmware 중 이 커넥터에 해당하는 파일 (없으면 None)"""
    try:
        vals = re.findall(r"(?:^|\s)drm\.edid_firmware=(\S+)", CMDLINE.read_text())
    except OSError:
        return None
    if not vals:
        return None
    entries = dict(ent.rpartition(":")[::2] for ent in vals[-1].split(","))
    return entries.get(conn) or entries.get("")


def lockdown():
    try:
        m = re.search(r"\[(\w+)\]", LOCKDOWN.read_text())
        return m.group(1) if m else None
    except OSError:
        return None


def link_caps(idx, conn):
    s = read_dbg(DEBUG_DRI / idx / conn / "link_settings")
    m = s and re.search(r"Current:\s+(\d+)\s+0x(\w+).*?Verified:\s+(\d+)\s+0x(\w+)", s, re.S)
    if not m:
        return None
    return (int(m[1]), int(m[2], 16)), (int(m[3]), int(m[4], 16))


def link_gbps(lanes, code):
    return lanes * (code / 100 * 0.9671 if code >= 1000 else code * 0.27 * 0.8)


def kernel_output(idx, conn):
    """debugfs state에서 실제 출력 중인 모드 (root 필요, lockdown에서도 읽힘)"""
    st = read_dbg(DEBUG_DRI / idx / "state")
    m = st and re.search(rf"connector\[\d+\]: {re.escape(conn)}\n((?:\t[^\n]*\n)*)", st)
    crtc = m and re.search(r"\tcrtc=(\S+)", m[1])
    if not crtc:
        return None
    if crtc[1] == "(null)":
        return {"off": True}
    c = re.search(rf"crtc\[\d+\]: {re.escape(crtc[1])}\n((?:\t[^\n]*\n)*)", st)
    mode = c and re.search(r'\tmode: "[^"]*": ([^\n]+)', c[1])
    if not mode:
        return None
    v = [int(x, 0) for x in mode[1].split()]
    bpc = read_dbg(DEBUG_DRI / idx / crtc[1] / "amdgpu_current_bpc")
    dsc = read_dbg(DEBUG_DRI / idx / conn / "dsc_clock_en")
    return {"off": False, "clk": v[1], "h": tuple(v[2:6]), "v": tuple(v[6:10]), "flags": v[11],
            "bpc": re.search(r"\d+", bpc)[0] if bpc else None, "dsc": dsc.strip() if dsc else None}


def mutter_output(conn):
    """GNOME(mutter)에 현재 모드 질의 (sudo 없이 실행했을 때)"""
    try:
        from gi.repository import Gio
        bus = Gio.bus_get_sync(Gio.BusType.SESSION, None)
        res = bus.call_sync("org.gnome.Mutter.DisplayConfig", "/org/gnome/Mutter/DisplayConfig",
                            "org.gnome.Mutter.DisplayConfig", "GetCurrentState",
                            None, None, Gio.DBusCallFlags.NONE, 3000, None)
        monitors = res.unpack()[1]
    except Exception:
        return None
    for spec, modes, _ in monitors:
        if spec[0] == conn:
            cur = next(((m[1], m[2], m[3]) for m in modes if m[6].get("is-current")), None)
            listed = any(m[1] == H_ACTIVE and m[2] == V_ACTIVE and abs(m[3] - REFRESH_HZ) < 0.05
                         for m in modes)
            return cur, listed
    return None


# ──────────────────────── 명령 ────────────────────────
def cmd_check(args):
    root = os.geteuid() == 0
    head("시스템")
    info(f"{os_name()}, 커널 {os.uname().release}")
    ld = lockdown()
    if ld and ld != "none":
        info(f"커널 lockdown: {ld} (Secure Boot) → 링크 속도·bpc·DSC 항목은 확인이 막힐 수 있음")

    card, conn, cpath = pick(args)
    idx = card.name[4:]
    head("GPU / 모니터")
    ok(f"AMD GPU: {card.name}  {gpu_name(card)}")
    e = read_edid(cpath)
    if not edid_ok(e):
        die(f"{conn} 의 EDID를 읽을 수 없습니다.")
    bpc = edid_bpc(e)
    ok(f"모니터: {conn}  \"{edid_name(e)}\"  EDID {e[18]}.{e[19]}, "
       f"{f'{bpc}bit' if bpc else '색심도 미기재'}, 확장: {', '.join(edid_exts(e)) or '없음'}")
    rng = edid_range(e)
    if rng:
        vmin, vmax, _, _, pmax = rng
        good = vmax >= REFRESH_HZ and pmax >= CLK_KHZ / 1000
        (ok if good else warn)(f"EDID 범위 정보: {vmin}–{vmax} Hz, 최대 {pmax} MHz "
                               f"(목표 {REFRESH_HZ:g} Hz, {CLK_KHZ / 1000:.2f} MHz)"
                               + ("" if good else " → 범위 밖 (참고용, 커널은 이 값으로 막지 않음)"))
    native = [t for t in displayid_timings(e) if t["h"][0] == H_ACTIVE and t["v"][0] == V_ACTIVE]
    for t in native:
        hz = t["clk"] * 1000 / (t["h"][3] * t["v"][3])
        info(f"EDID 내 DisplayID 타이밍: {H_ACTIVE}x{V_ACTIVE} @ {hz:.2f} Hz, {t['clk'] / 1000:.2f} MHz"
             + ("  ← 목표 타이밍" if is_target(t) else ""))

    head("DP 링크")
    lc = link_caps(idx, conn) if root else None
    if lc:
        (cl, cr), (vl, vr) = lc
        cap = link_gbps(vl, vr)
        info(f"현재 {cl} lane × {RATES.get(cr, hex(cr))}, 최대(검증) {vl} lane × {RATES.get(vr, hex(vr))}"
             f" = 실효 {cap:.2f} Gbps")
        (ok if cap >= NEED_GBPS else warn)(
            f"필요 {NEED_GBPS:.2f} Gbps (8bit RGB) → "
            + ("DSC 없이 가능" if cap >= NEED_GBPS else "대역폭 부족: DSC가 켜지거나 모드가 거부될 수 있음"))
    else:
        info(f"필요 대역폭 {NEED_GBPS:.2f} Gbps (8bit RGB, UHBR13.5 4lane이면 DSC 없이 가능)"
             + ("" if root else " — 링크 속도는 sudo로 실행하면 확인"))

    head("오버라이드 설정")
    custom = FW_DIR / f"custom-{conn}.bin"
    param = f"{conn}:edid/custom-{conn}.bin"
    info(f"펌웨어 {custom}: {'있음' if custom.exists() else '없음'}")
    info(f"initramfs 훅 {HOOK}: {'있음' if HOOK.exists() else '없음'}")
    dropin = GRUB_DROPIN.read_text() if GRUB_DROPIN.exists() else ""
    info(f"GRUB 설정 {GRUB_DROPIN}: {'있음' if param in dropin else '없음'}")
    if GRUB_MAIN.exists() and "drm.edid_firmware" in GRUB_MAIN.read_text():
        warn(f"{GRUB_MAIN} 에 수동으로 넣은 drm.edid_firmware가 있습니다 (중복이면 지워 주세요)")
    fw = cmdline_override(conn)
    active = bool(fw) and (FW_ROOT / fw).exists() and (FW_ROOT / fw).read_bytes() == e
    if fw:
        (ok if active else warn)(f"현재 부팅 파라미터: drm.edid_firmware → {fw} "
                                 + ("(적용됨)" if active else "(로드 실패 또는 파일 불일치)"))
    else:
        info("현재 부팅에는 EDID 오버라이드 없음")
    (ok if has_target(e) else info)(f"현재 EDID에 {REFRESH_HZ:g} Hz 타이밍: {'있음' if has_target(e) else '없음'}")

    head("현재 출력")
    hit = False
    if root:
        k = kernel_output(idx, conn)
        if k and k["off"]:
            info("이 커넥터는 현재 꺼져 있음")
        elif k:
            hz = k["clk"] * 1000 / (k["h"][3] * k["v"][3])
            hit = k["h"] == T_H and k["v"] == T_V and abs(k["clk"] - CLK_KHZ) <= 10
            pol = f"{'+' if k['flags'] & 1 else '-'}h {'+' if k['flags'] & 4 else '-'}v"
            (ok if hit else info)(f"{k['h'][0]}x{k['v'][0]} @ {hz:.2f} Hz, {k['clk'] / 1000:.2f} MHz, "
                                  f"{' '.join(map(str, k['h'] + k['v']))} {pol}")
            if k["bpc"] or k["dsc"]:
                bad = (k["bpc"] and k["bpc"] != "8") or k["dsc"] == "1"
                (warn if bad else ok)(f"출력 bpc: {k['bpc'] or '?'}, DSC: "
                                      + {"0": "꺼짐", "1": "켜짐"}.get(k["dsc"], "?"))
            else:
                info("bpc·DSC 상태는 lockdown 때문에 확인 불가")
        else:
            info("debugfs에서 현재 모드를 읽지 못했습니다")
    else:
        mo = mutter_output(conn)
        if mo:
            cur, listed = mo
            hit = bool(cur) and cur[:2] == (H_ACTIVE, V_ACTIVE) and abs(cur[2] - REFRESH_HZ) < 0.05
            if cur:
                (ok if hit else info)(f"GNOME 현재 모드: {cur[0]}x{cur[1]} @ {cur[2]:.2f} Hz")
            info(f"GNOME 모드 목록에 {REFRESH_HZ:g} Hz: {'있음' if listed else '없음'}")
        else:
            info("GNOME에서 모드를 읽지 못했습니다 (sudo로 실행하면 커널 기준으로 확인)")

    head("결론")
    if hit:
        ok(f"{H_ACTIVE}x{V_ACTIVE} @ {REFRESH_HZ:g} Hz 로 출력 중입니다.")
    elif has_target(e):
        info(f"모드는 준비됨 → 설정 > 디스플레이에서 주사율 {REFRESH_HZ:.2f} Hz 를 선택하세요.")
    elif custom.exists() and param in dropin:
        info("설정은 끝났고 아직 적용 전입니다 → 재부팅하세요.")
    else:
        info("sudo python3 amd_custom_mode.py install 로 설정하세요.")


def confirm(args, msg):
    if args.yes:
        return
    try:
        answer = input(f"\n{msg} [y/N] ").strip().lower()
    except EOFError:
        answer = ""
    if answer not in ("y", "yes"):
        die("취소했습니다.")


def need_root():
    if os.geteuid() != 0:
        die("관리자 권한이 필요합니다: sudo python3 amd_custom_mode.py ...")


def update_boot_files():
    head("initramfs / GRUB 갱신")
    if not run(["update-initramfs", "-u", "-k", "all"]):
        die("update-initramfs 실패")
    if not run(["update-grub"]):
        die("update-grub 실패")


def cmd_install(args):
    need_root()
    for tool in ("update-initramfs", "update-grub", "lsinitramfs"):
        if not shutil.which(tool):
            die(f"{tool} 명령이 없습니다 (Ubuntu 기본 initramfs-tools·GRUB 환경이 아님)")
    card, conn, cpath = pick(args)
    cur = read_edid(cpath)
    if not edid_ok(cur):
        die(f"{conn} 의 EDID를 읽을 수 없습니다.")
    orig, custom = FW_DIR / f"original-{conn}.bin", FW_DIR / f"custom-{conn}.bin"

    # 오버라이드가 이미 적용 중이면 sysfs EDID는 수정본이므로 저장해 둔 원본에서 다시 만든다
    if cmdline_override(conn) or has_target(cur):
        if orig.exists():
            base = orig.read_bytes()
        elif has_target(cur):
            base = None
        else:
            die("EDID 오버라이드가 이미 적용 중이라 원본 EDID를 알 수 없습니다.\n"
                "  uninstall → 재부팅 → install 순서로 진행해 주세요.")
    else:
        base = cur
    new = build_edid(base) if base else force_8bpc(cur)
    t = next(t for t in displayid_timings(new) if is_target(t))

    head("설정 내용")
    info(f"대상: {card.name} {conn}  \"{edid_name(cur)}\"")
    info(f"추가 모드: {H_ACTIVE}x{V_ACTIVE} @ {t['clk'] * 1000 / (HT * VT):.3f} Hz, {t['clk'] / 1000:.3f} MHz, "
         f"{' '.join(map(str, T_H + T_V))} {'+' if H_POS else '-'}h {'+' if V_POS else '-'}v")
    if FORCE_8BPC:
        info(f"EDID 색심도: {edid_bpc(cur) or '?'}bit → {edid_bpc(new) or '?'}bit 표기")
    info(f"파일: {custom}, {HOOK}, {GRUB_DROPIN}")
    if GRUB_MAIN.exists() and "drm.edid_firmware" in GRUB_MAIN.read_text():
        warn(f"{GRUB_MAIN} 에 수동으로 넣은 drm.edid_firmware가 있습니다. 이 스크립트 값이 뒤에 붙어 "
             "우선 적용되지만, 헷갈리지 않게 지워 주세요.")
    confirm(args, "진행할까요?")

    FW_DIR.mkdir(parents=True, exist_ok=True)
    if base is cur:
        orig.write_bytes(cur)                     # 원본 EDID 백업
    custom.write_bytes(new)
    HOOK.parent.mkdir(parents=True, exist_ok=True)
    HOOK.write_text(HOOK_SH)
    HOOK.chmod(0o755)
    entries = ",".join(f"{f.stem[7:]}:edid/{f.name}" for f in sorted(FW_DIR.glob("custom-*.bin")))
    GRUB_DROPIN.parent.mkdir(parents=True, exist_ok=True)
    GRUB_DROPIN.write_text("# generated by amd_custom_mode.py (remove: sudo python3 amd_custom_mode.py uninstall)\n"
                           f'GRUB_CMDLINE_LINUX_DEFAULT="$GRUB_CMDLINE_LINUX_DEFAULT drm.edid_firmware={entries}"\n')
    update_boot_files()

    head("검증")
    (ok if initrd_has(f"edid/{custom.name}") else warn)(f"현재 커널 initramfs에 {custom.name} 포함")
    grub_ok = GRUB_CFG.exists() and f"drm.edid_firmware={entries}" in GRUB_CFG.read_text()
    (ok if grub_ok else warn)(f"{GRUB_CFG} 에 drm.edid_firmware={entries} 반영")
    print(f"\n완료. 재부팅 후 설정 > 디스플레이에서 주사율 {REFRESH_HZ:.2f} Hz 를 선택하고,\n"
          "sudo python3 amd_custom_mode.py check 로 실제 출력 상태를 확인하세요.")


def cmd_uninstall(args):
    need_root()
    targets = [x for x in [GRUB_DROPIN, HOOK, *sorted(FW_DIR.glob("custom-*.bin"))] if x.exists()]
    if not targets:
        die("이 스크립트로 설정한 항목이 없습니다.")
    head("제거할 파일")
    for x in targets:
        info(str(x))
    confirm(args, "제거할까요?")
    for x in targets:
        x.unlink()
    update_boot_files()
    print("\n완료. 재부팅하면 원래 EDID로 돌아갑니다. (원본 백업 original-*.bin 은 남겨 둠)")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("command", nargs="?", default="check", choices=["check", "install", "uninstall"])
    ap.add_argument("--connector", help="대상 커넥터 (예: DP-1)")
    ap.add_argument("--yes", action="store_true", help="확인 질문 생략")
    args = ap.parse_args()
    {"check": cmd_check, "install": cmd_install, "uninstall": cmd_uninstall}[args.command](args)


if __name__ == "__main__":
    main()
